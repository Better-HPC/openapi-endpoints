/** Unit tests for the `generate` function. */

import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { describe, it } from "node:test";

import { parseOpenApiText } from "../src/openapi.ts";
import { generate, GENERATED_NAMES } from "../src/generate.ts";
import { buildDocument, fixturePath, readFixture, typeCheck } from "./support.ts";

/** Generated module for the example fixture, which is shared by several tests. */
const EXAMPLE_OUTPUT = generate(parseOpenApiText(readFixture("example.yml")), {source: "example.yml"});

/** Type level assertions about the module generated from the example fixture. */
const EXAMPLE_ASSERTIONS = `
import type {
  EndpointMethod,
  EndpointOperation,
  EndpointPathParams,
  EndpointPathsWith,
  EndpointQueryParams,
  EndpointRequestBody,
  EndpointResponse,
  EndpointStatusResponse,
  PaginatedTeamList,
  Team,
  TeamRequest,
  UserSummary,
} from "./api";

type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends (<T>() => T extends B ? 1 : 2) ? true : false;
type Assert<T extends true> = T;

export type Checks = [
  Assert<Equal<EndpointResponse<"/teams/", "get">, PaginatedTeamList>>,
  Assert<Equal<EndpointRequestBody<"/teams/", "post">, TeamRequest>>,
  Assert<Equal<EndpointResponse<"/teams/", "post">, Team>>,
  Assert<Equal<EndpointStatusResponse<"/teams/", "post", 400>, { [key: string]: string[] }>>,
  Assert<Equal<EndpointPathParams<"/teams/{id}/", "get">, { id: number }>>,
  Assert<Equal<EndpointPathParams<"/teams/", "get">, never>>,
  Assert<Equal<
    EndpointQueryParams<"/teams/", "get">,
    { _limit?: number; _search?: string; id__in?: number[]; role?: "OW" | "AD" | "MB" }
  >>,
  Assert<Equal<EndpointResponse<"/teams/{id}/", "delete">, void>>,
  Assert<Equal<EndpointResponse<"/version/", "get">, unknown>>,
  Assert<Equal<EndpointResponse<"/logout/", "get">, never>>,
  Assert<Equal<EndpointOperation<"/logout/", "get">, never>>,
  Assert<Equal<EndpointMethod<"/teams/{id}/">, "get" | "delete" | "patch">>,
  Assert<Equal<EndpointPathsWith<"post">, "/batch/" | "/logout/" | "/teams/">>,
  Assert<Equal<Team["_owner"], UserSummary | null>>,
  Assert<Equal<UserSummary["email"], string | null | undefined>>,
];

declare function request<P extends EndpointPathsWith<"get">>(
  path: P,
  options?: {pathParams?: EndpointPathParams<P, "get">; queryParams?: EndpointQueryParams<P, "get">},
): EndpointResponse<P, "get">;

export const team: Team = request("/teams/{id}/", {pathParams: {id: 1}});
export const teams: PaginatedTeamList = request("/teams/", {queryParams: {id__in: [1, 2], role: "AD"}});

// @ts-expect-error The path does not define a GET operation
request("/logout/");

// @ts-expect-error Query parameters must match the schema
request("/teams/", {queryParams: {role: "XX"}});
`;

describe("GeneratedModule", () => {
  it("Verify the generated module type checks and matches the expected types", async () => {
    const diagnostics = await typeCheck({"api.ts": EXAMPLE_OUTPUT, "checks.ts": EXAMPLE_ASSERTIONS});
    assert.deepEqual(diagnostics, [], "Generated module failed to type check");
  });

  it("Verify the generated module matches the reviewed fixture output", () => {
    // Set UPDATE_FIXTURES=1 to accept intentional changes to the generated output
    if (process.env["UPDATE_FIXTURES"]) {
      writeFileSync(fixturePath("example.ts"), EXAMPLE_OUTPUT, "utf8");
    }

    assert.equal(EXAMPLE_OUTPUT, readFixture("example.ts"), "Generated output differs from test/fixtures/example.ts");
  });

  it("Verify the generated module only contains type declarations", () => {
    const declarations = EXAMPLE_OUTPUT.split("\n").filter((line) => line.startsWith("export "));
    for (const line of declarations) {
      assert.match(line, /^export (interface|type) /, `Unexpected runtime declaration: ${line}`);
    }
  });

  it("Verify every generated helper name is reserved", () => {
    for (const name of GENERATED_NAMES) {
      assert.match(EXAMPLE_OUTPUT, new RegExp(`^export (interface|type) ${name}\\b`, "m"), `${name} is not declared`);
    }
  });
});

describe("HeaderComment", () => {
  it("Verify the header names the document, version, and source", () => {
    assert.ok(EXAMPLE_OUTPUT.startsWith("/**\n * TypeScript definitions for Example API (version 1.2.0).\n"));
    assert.match(EXAMPLE_OUTPUT, /generated by openapi-endpoints from `example.yml`/);
  });

  it("Verify the header falls back to a generic description without document info", () => {
    const output = generate({openapi: "3.1.0"});
    assert.ok(output.startsWith("/**\n * TypeScript definitions for an OpenAPI document.\n"));
    assert.doesNotMatch(output, / from `/);
  });
});

describe("Determinism", () => {
  it("Verify the output does not depend on the order of paths and schemas", () => {
    const schemas = {B: {type: "string"}, A: {type: "integer"}};
    const paths = {"/b/": {get: {responses: {}}}, "/a/": {get: {responses: {}}}};
    const reversed = {
      paths: Object.fromEntries(Object.entries(paths).reverse()),
      components: {schemas: Object.fromEntries(Object.entries(schemas).reverse())},
    };

    assert.equal(generate(buildDocument({paths, components: {schemas}})), generate(buildDocument(reversed)));
  });
});

describe("EmptyDocuments", () => {
  it("Verify a document without paths or schemas produces a valid module", async () => {
    const output = generate({openapi: "3.0.3", info: {title: "Empty", version: "0"}});
    assert.match(output, /export interface Endpoints \{\}/);
    assert.deepEqual(await typeCheck({"api.ts": output}), []);
  });
});

describe("NameConflicts", () => {
  it("Verify schemas named after generated declarations are rejected", () => {
    const document = buildDocument({components: {schemas: {Endpoints: {type: "object"}}}});
    assert.throws(() => generate(document), /Schema name "Endpoints" conflicts with a reserved type name/);
  });
});
